pub struct Engine {
    pub size: usize,
    pub layers: Vec<LayerData>,
    pub active: String,
    pub reference: Option<Buf>,
    pub composite: Buf,
    pub prev_composite: Buf,
    scratch: Buf,
    pub     projection: Projection,
    pub polar_angle: f32,
    pub full_dirty: bool,
    history: Vec<HistoryEntry>,
    hist_idx: usize,
    id_counter: u64,
    /// Per-pixel deposit weight for the stroke in progress. See `ops::stamp`.
    /// Only meaningful while painting a flow layer; `None` clears it.
    stroke_accum: Vec<u8>,
    /// Which (layer, stroke) `stroke_accum` belongs to. `None` means stale.
    stroke_key: Option<(String, u64)>,
    /// Region of the composite that the next `composite()` has to rebuild.
    /// `None` means the composite is already current.
    ///
    /// Blending is pointwise, so "what changed" is exactly "where the layer
    /// changed" — plus a margin for blur. This is what keeps a 64px dab from
    /// costing a 1024px recomposite.
    pending: Option<(usize, usize, usize, usize)>,
    /// Region the last `composite()` rebuilt. `dirty_rect` scans only this, so
    /// the diff costs as much as the edit rather than as much as the canvas.
    last_region: (usize, usize, usize, usize),
    /// Second reusable buffer: the masked copy of a wind / obstacle layer.
    scratch2: Buf,
}

impl Engine {
    pub fn new(size: usize) -> Self {
        let paint = LayerData {
            p: LayerParams {
                id: "layer-1".into(),
                name: "流向 1".into(),
                kind: LayerKind::Paint,
                visible: true,
                opacity: 1.0,
                effects: Vec::new(),
                legacy_blur: 0.0,
                direction: 0.0,
                strength: 0.0,
                has_mask: false,
            },
            buf: Buf::new(size, size),
            mask: None,
            paths: Vec::new(),
            wind_dirty: false,
            buf_dirty: true,
            mask_dirty: true,
            blur_cache: None,
            plane_cache: None,
        };
        let wind = LayerData {
            p: LayerParams {
                id: "wind-default".into(),
                name: "全局风向".into(),
                kind: LayerKind::Wind,
                visible: true,
                opacity: 1.0,
                effects: Vec::new(),
                legacy_blur: 0.0,
                direction: 45.0,
                strength: 0.5,
                has_mask: false,
            },
            buf: Buf::new(size, size),
            mask: None,
            paths: Vec::new(),
            wind_dirty: true,
            buf_dirty: true,
            mask_dirty: true,
            blur_cache: None,
            plane_cache: None,
        };
        Self {
            size,
            layers: vec![wind, paint],
            active: "layer-1".into(),
            reference: None,
            composite: Buf::filled(size, size, buf::NEUTRAL),
            prev_composite: Buf::filled(size, size, buf::NEUTRAL),
            scratch: Buf::filled(size, size, buf::NEUTRAL),
            scratch2: Buf::filled(size, size, buf::NEUTRAL),
            projection: Projection::Equirectangular,
            polar_angle: 90.0,
            full_dirty: true,
            history: Vec::new(),
            hist_idx: 0,
            id_counter: 1,
            stroke_accum: Vec::new(),
            stroke_key: None,
            pending: None,
            last_region: (0, 0, 0, 0),
        }
    }

    /// Drop the per-stroke deposit record. Anything that rewrites layer pixels
    /// outside of `stroke` has to call this: the accumulator is a delta against
    /// pixels that no longer exist, so keeping it would make the next stroke
    /// deposit too little.
    fn invalidate_accum(&mut self) {
        self.stroke_key = None;
    }

    pub fn resize(&mut self, size: usize) {
        if size == self.size {
            return;
        }
        let old = self.size;
        self.size = size;
        for l in self.layers.iter_mut() {
            // Paths are in UV, so they survive a resize untouched — but their
            // raster does not: regenerating from the anchors at the new size is
            // the whole reason a path layer is resolution independent.
            if l.p.kind == LayerKind::Path {
                l.buf = Buf::new(size, size);
                generate_paths(&mut l.buf, &l.paths);
            } else {
                l.buf = ops::upscale(&l.buf, size, size);
            }
            if let Some(m) = l.mask.take() {
                l.mask = Some(ops::upscale(&m, size, size));
            }
            l.wind_dirty = true;
            l.buf_dirty = true;
            l.mask_dirty = true;
            // Both caches are keyed on a radius, not on a size — a resized
            // buffer would silently read back at the wrong dimensions.
            l.blur_cache = None;
            l.plane_cache = None;
        }
        if let Some(r) = self.reference.take() {
            self.reference = Some(ops::upscale(&r, size, size));
        }
        self.composite = Buf::filled(size, size, buf::NEUTRAL);
        self.prev_composite = Buf::filled(size, size, buf::NEUTRAL);
        self.scratch = Buf::filled(size, size, buf::NEUTRAL);
        self.scratch2 = Buf::filled(size, size, buf::NEUTRAL);
        self.history.clear();
        self.hist_idx = 0;
        self.full_dirty = true;
        self.pending = None;
        self.last_region = (0, 0, 0, 0);
        self.stroke_accum.clear();
        self.invalidate_accum();
        let _ = old;
    }

    pub fn layer_mut(&mut self, id: &str) -> Option<&mut LayerData> {
        self.layers.iter_mut().find(|l| l.p.id == id)
    }

    pub fn layer(&self, id: &str) -> Option<&LayerData> {
        self.layers.iter().find(|l| l.p.id == id)
    }

    /// A small stand-in for one layer, for the 图层 panel's thumbnail column.
    ///
    /// It shows the layer's **own** pixels, not its contribution to the
    /// composite — which is what Photoshop does, and what makes the column
    /// readable: dragging a layer up the stack does not change its thumbnail,
    /// so you can still tell which row you are looking at mid-drag.
    ///
    /// What "its own pixels" means differs per kind:
    ///   * paint    — the stroke buffer. Unpainted area is (0,0,0,0), so the
    ///                thumbnail shows strokes on transparency, like PS.
    ///   * wind     — the generated vector field, which is what the layer is.
    ///   * obstacle — the **mask**. An obstacle layer's `buf` is never drawn
    ///                (the composite reads `obstacle_alpha_plane(mask)`), so the
    ///                mask is the only part of it a human recognises.
    pub fn layer_thumb(&self, l: &LayerData, tw: usize, th: usize) -> Buf {
        if l.p.kind != LayerKind::Obstacle {
            return ops::downscale(&l.buf, tw, th);
        }
        let Some(m) = l.mask.as_ref() else {
            return Buf::new(tw, th);
        };
        // Recolour first, shrink second: the mask is greyscale, and a grey
        // thumbnail on a grey panel is unreadable. Averaging the recoloured
        // buffer is also what gives the shape a soft edge instead of a
        // point-sampled dotted one.
        let mut plate = Buf::new(m.w, m.h);
        for (o, i) in plate.data.chunks_exact_mut(4).zip(m.data.chunks_exact(4)) {
            o[0] = 226;
            o[1] = 232;
            o[2] = 240;
            o[3] = i[0];
        }
        ops::downscale(&plate, tw, th)
    }

    // -- layer management ----------------------------------------------------

    pub fn add_layer(&mut self, kind: LayerKind) -> String {
        self.id_counter += 1;
        let id = format!("{}-{}", kind_name(&kind), self.id_counter);
        let count = self.layers.iter().filter(|l| l.p.kind == kind).count();
        let name = match kind {
            LayerKind::Paint => format!("流向 {}", count + 1),
            LayerKind::Wind => "风向".to_string(),
            LayerKind::Obstacle => "障碍物".to_string(),
            LayerKind::Path => format!("路径 {}", count + 1),
        };
        let p = LayerParams {
            id: id.clone(),
            name,
            kind: kind.clone(),
            visible: true,
            opacity: 1.0,
            effects: Vec::new(),
            legacy_blur: 0.0,
            direction: 45.0,
            strength: 0.5,
            has_mask: false,
        };
        self.layers.push(LayerData {
            p,
            buf: Buf::new(self.size, self.size),
            mask: None,
            paths: Vec::new(),
            wind_dirty: true,
            buf_dirty: true,
            mask_dirty: true,
            blur_cache: None,
            plane_cache: None,
        });
        self.active = id.clone();
        self.full_dirty = true;
        id
    }

    pub fn remove_layer(&mut self, id: &str) -> bool {
        if self.layers.len() <= 1 {
            return false;
        }
        if let Some(i) = self.layers.iter().position(|l| l.p.id == id) {
            self.layers.remove(i);
            if self.active == id {
                self.active = self.layers[self.layers.len() - 1].p.id.clone();
            }
            self.full_dirty = true;
            true
        } else {
            false
        }
    }

    /**
     * Merge a layer into the one below it — Photoshop's 向下合并.
     *
     * The result has to be *indistinguishable* from the two layers it
     * replaces, or merging is a way of quietly losing your work. For content
     * layers that is exact: `over` is associative, and a layer's opacity only
     * ever enters as `alpha * opacity`, so folding both opacities into the
     * alpha of one layer reproduces the stack bit for bit.
     *
     * What is *not* exact is refused rather than approximated:
     *
     * - **Different kinds.** A mask and a pixel buffer are not the same kind
     *   of thing, and there is no honest way to add one to the other.
     * - **Wind.** A wind layer *is* its two parameters; its pixels are a cache
     *   of them that the next composite overwrites. Merging two would keep one
     *   pair of dials and throw the other away, and the thrown-away pair is
     *   exactly the thing you spent time tuning.
     * - **Different blur radii.** One radius cannot express two. (Equal radii
     *   are fine: the merge is done on un-blurred pixels and the effect rides
     *   along, so the composite still blurs once.)
     * - **A path layer whose opacity differs from the one below.** Opacity
     *   there multiplies alpha, and a path has no per-path alpha of its own —
     *   only a strength, which moves the vector, not the coverage.
     */
    pub fn merge_down(&mut self, id: &str) -> bool {
        let n = self.size;
        let i = match self.layers.iter().position(|l| l.p.id == id) {
            Some(i) if i > 0 => i,
            _ => return false,
        };
        let kind = self.layers[i].p.kind.clone();
        if kind != self.layers[i - 1].p.kind {
            return false;
        }
        match kind {
            LayerKind::Wind => return false,
            LayerKind::Paint | LayerKind::Path | LayerKind::Obstacle => {}
        }
        let r_up = blur_amount(&self.layers[i].p.effects);
        let r_low = blur_amount(&self.layers[i - 1].p.effects);
        if (r_up - r_low).abs() > 0.01 {
            return false;
        }
        if kind == LayerKind::Path
            && (self.layers[i].p.opacity - self.layers[i - 1].p.opacity).abs() > 1e-4
        {
            return false;
        }

        let lower_id = self.layers[i - 1].p.id.clone();
        self.save_history_stack(&[lower_id.clone(), id.to_string()]);

        match kind {
            LayerKind::Paint => {
                let mut merged = self.layers[i - 1].buf.clone();
                merge_over(
                    &mut merged,
                    &self.layers[i].buf,
                    self.layers[i - 1].p.opacity,
                    self.layers[i].p.opacity,
                );
                let lower = &mut self.layers[i - 1];
                lower.buf = merged;
                lower.p.opacity = 1.0;
                lower.buf_dirty = true;
                lower.blur_cache = None;
            }
            LayerKind::Obstacle => {
                // The mask is the layer, so merging is a union of two masks —
                // with the same over-compositing as anywhere else, so a pixel
                // both masks cover is not double-counted.
                let mut merged: Option<Buf> = self.layers[i - 1].mask.clone();
                match (merged.as_mut(), self.layers[i].mask.as_ref()) {
                    (Some(m), Some(up)) => {
                        merge_over(m, up, self.layers[i - 1].p.opacity, self.layers[i].p.opacity)
                    }
                    // Only one side has a mask, so there is nothing to flatten
                    // against — just fold its opacity into the alpha.
                    (Some(m), None) => scale_alpha(m, self.layers[i - 1].p.opacity),
                    (None, Some(up)) => {
                        let mut m = up.clone();
                        scale_alpha(&mut m, self.layers[i].p.opacity);
                        merged = Some(m);
                    }
                    (None, None) => {}
                }
                // Two reaches acting on two different masks cannot be one
                // reach acting on their union, so the larger wins — the same
                // rule as two blurs, and for the same reason.
                let d = disturbance_amount(&self.layers[i - 1].p.effects)
                    .max(disturbance_amount(&self.layers[i].p.effects));
                let lower = &mut self.layers[i - 1];
                lower.mask = merged;
                lower.p.has_mask = lower.mask.is_some();
                lower.p.opacity = 1.0;
                lower.p.effects = if d > 0.0 {
                    vec![LayerEffect::disturbance(d)]
                } else {
                    Vec::new()
                };
                lower.mask_dirty = true;
                lower.plane_cache = None;
            }
            LayerKind::Path => {
                // Geometry, not pixels: the paths of both layers simply become
                // the paths of one. Nothing is baked, so the result is still
                // editable — which is the whole point of a path layer.
                let mut all = self.layers[i - 1].paths.clone();
                all.extend(self.layers[i].paths.iter().cloned());
                let lower = &mut self.layers[i - 1];
                lower.paths = all;
                generate_paths(&mut lower.buf, &lower.paths);
                lower.buf_dirty = true;
                lower.blur_cache = None;
            }
            LayerKind::Wind => unreachable!(),
        }

        self.layers.remove(i);
        self.active = lower_id;
        // ...and the state *after*, so redo has somewhere to go.
        let after = snapshot_of(&self.layers[i - 1]);
        let order: Vec<String> = self.layers.iter().map(|l| l.p.id.clone()).collect();
        self.push_history(vec![after], Some(order));

        self.full_dirty = true;
        self.invalidate_accum();
        true
    }

    /// Move a layer in the visual (top-first) ordering. `from`/`to` are indices
    /// in the reversed list, matching the UI.
    pub fn reorder_visual(&mut self, from: usize, to: usize) {
        let n = self.layers.len();
        if from >= n || to >= n {
            return;
        }
        let a = n - 1 - from;
        let b = n - 1 - to;
        let l = self.layers.remove(a);
        self.layers.insert(b, l);
        self.full_dirty = true;
    }

    // -- painting ------------------------------------------------------------

    /// Apply a polyline of UV points to the active layer. Returns the dirty
    /// bounding box in pixels.
    ///
    /// `stroke_id` identifies the pointer stroke these points belong to. The
    /// frontend sends one batch per animation frame, so without it there is no
    /// way to tell "more of the same drag" from "a second pass over the same
    /// spot" — and that distinction is exactly what makes low-strength brushes
    /// build up. It only has to change when a new stroke starts.
    pub fn stroke(
        &mut self,
        pts: &[(f32, f32)],
        size: f32,
        hardness: f32,
        strength: f32,
        erase: bool,
        target: &str,
        stroke_id: u64,
        flow: f32,
    ) -> Option<(usize, usize, usize, usize)> {
        let active_id = self.active.clone();
        let layer = self.layer(&active_id)?;
        let is_adj = matches!(layer.p.kind, LayerKind::Wind | LayerKind::Obstacle);
        // Adjustment layers have no paintable content — their pixels are
        // generated from parameters. Painting one always edits its mask, so the
        // brush can never silently do nothing because of a UI mode.
        let _ = target;

        // flow colour is derived per-segment from the drag direction
        let mut out: Option<(usize, usize, usize, usize)> = None;

        let n = self.size;

        // Deposit bookkeeping for the current stroke. Only flow layers build
        // up; a mask's alpha is its payload and has nothing to accumulate
        // towards.
        //
        // Moved out of `self` for the duration of the loop — the layer buffer
        // below is borrowed from `self` too, and they are different fields.
        let key = Some((active_id.clone(), stroke_id));
        let mut accum_opt: Option<Vec<u8>> = if is_adj {
            None
        } else {
            let mut a = std::mem::take(&mut self.stroke_accum);
            if a.len() != n * n {
                a = vec![0u8; n * n];
                self.stroke_key = None;
            }
            if self.stroke_key.as_ref() != key.as_ref() {
                a.fill(0);
                self.stroke_key = key;
            }
            Some(a)
        };

        {
            let layer = self.layer_mut(&active_id).unwrap();
            let dst: &mut Buf = if is_adj {
                if layer.mask.is_none() {
                    // Starts EMPTY (alpha 0). A mask that began fully opaque
                    // would mark the entire sky as obstacle on the first dab.
                    layer.mask = Some(Buf::new(n, n));
                    layer.p.has_mask = true;
                }
                layer.mask.as_mut().unwrap()
            } else {
                &mut layer.buf
            };

            let is_mask = is_adj;
            let mut prev: Option<(f32, f32)> = None;
            let last = pts.len().saturating_sub(1);
            for (i, &(u, v)) in pts.iter().enumerate() {
                let (x, y) = (u * n as f32, v * n as f32);
                // Capsule start. With no previous sample this collapses to the
                // point itself, i.e. a round dab.
                let (lx, ly) = match prev {
                    Some((lu, lv)) => (lu * n as f32, lv * n as f32),
                    None => (x, y),
                };
                // Direction of travel, used for the flow colour. The first
                // sample has no incoming segment, so look *ahead* along the
                // polyline.
                //
                // This used to be faked as a 0.01px horizontal offset, which
                // meant the first sample of every batch stamped a dot pointing
                // hard right. Because the frontend sends `[lastPoint, ...new]`
                // once per animation frame, that was one saturated blue speck
                // per frame, all the way along the stroke.
                let (dx, dy) = match prev {
                    Some(_) => (x - lx, y - ly),
                    None if i < last => {
                        let (nu, nv) = pts[i + 1];
                        ((nu - u) * n as f32, (nv - v) * n as f32)
                    }
                    None => (0.0, 0.0),
                };
                let d = (dx * dx + dy * dy).sqrt();
                // Below half a pixel there is no direction to speak of.
                //
                // For a paint layer that means there is nothing to draw — a
                // click with no drag is a no-op, exactly as the original web app
                // behaved (its stamp early-returned under 0.5px). Inventing a
                // direction here is what produced the speckle bug in the first
                // place. Nothing is lost when dragging: the next batch re-sends
                // this sample as its first element and paints the real segment.
                //
                // A mask has no direction to begin with, so a click on an
                // adjustment layer is a meaningful dab and must land.
                if d < 0.5 && !is_mask {
                    prev = Some((u, v));
                    continue;
                }
                let st = if is_mask {
                    StampStyle { r: 255, g: 255, b: 255, erase, opaque: true, flow: 1.0 }
                } else {
                    let vx = dx / d;
                    let vy = dy / d;
                    // `strength` is the *ceiling*, not the rate — it is the
                    // length of the flow vector you are aiming at, the same job
                    // the foreground colour does in Photoshop. `flow` is how
                    // quickly repeated strokes get there.
                    //
                    // Strength used to be the rate with the ceiling pinned at
                    // full, which meant a weak brush crept up to full strength
                    // if you kept painting — wrong for a vector field, where
                    // "this area flows gently" is a thing you mean.
                    let mut st = ops::flow_style(vx, vy, strength);
                    st.erase = erase;
                    st.flow = flow;
                    st
                };
                let r = self::stamp_wrap(dst, x, y, lx, ly, size, hardness, &st, accum_opt.as_deref_mut());
                out = merge_rect(out, r);
                prev = Some((u, v));
            }
        }
        if let Some(a) = accum_opt {
            self.stroke_accum = a;
        }
        let rect = out.unwrap_or((0, 0, 0, 0));
        if let Some(l) = self.layer_mut(&active_id) {
            if is_adj {
                l.mask_dirty = true;
            } else {
                l.buf_dirty = true;
            }
        }
        if rect.2 == 0 || rect.3 == 0 {
            return Some(rect);
        }
        if is_adj {
            // The dab is small but the obstacle plane it feeds is blurred by
            // hundreds of pixels, so the disturbance moves far outside the
            // brush. Not to the far side of the canvas though: grow the rect by
            // that reach rather than calling everything dirty. `full_dirty`
            // here cost a full recomposite *and* a full-canvas round trip on
            // every dab of an obstacle stroke — 7.2 ms and 4 MB at 1024², sixty
            // times a second.
            let reach = self
                .layers
                .iter()
                .filter(|l| l.p.id == active_id)
                .map(Self::obstacle_reach)
                .max()
                .unwrap_or(0);
            self.pending = merge_rect(self.pending, Self::grow_rect(rect, reach, self.size));
        } else {
            self.pending = merge_rect(self.pending, rect);
        }
        Some(rect)
    }

    /// Eyedropper: the flow strength under a UV point, on the active layer or
    /// on the composite, averaged over a 3x3 patch.
    ///
    /// Averaging matters because the field is 8-bit — a single pixel quantises
    /// to a jittery value, and the slider would land on something the user did
    /// not draw.
    ///
    /// A mask (wind / obstacle) has no flow strength to speak of, so sampling
    /// "the current layer" there falls back to the composite rather than
    /// reporting the mask's opaque white as a full-strength flow.
    pub fn sample_strength(&self, u: f32, v: f32, source: &str) -> f32 {
        let n = self.size;
        let layer_buf: Option<&Buf> = if source == "composite" {
            None
        } else {
            match self.layer(&self.active) {
                Some(l) if !matches!(l.p.kind, LayerKind::Wind | LayerKind::Obstacle) => Some(&l.buf),
                _ => None,
            }
        };
        let src: &Buf = layer_buf.unwrap_or(&self.composite);

        let cx = (u * n as f32).floor() as i32;
        let cy = (v * n as f32).floor() as i32;
        let mut sr = 0.0f32;
        let mut sg = 0.0f32;
        let mut count = 0usize;
        for dy in -1..=1i32 {
            let y = (cy + dy).clamp(0, n as i32 - 1) as usize;
            for dx in -1..=1i32 {
                let x = wrap_i((cx + dx) as isize, n);
                let i = (y * n + x) * 4;
                sr += src.data[i] as f32;
                sg += src.data[i + 1] as f32;
                count += 1;
            }
        }
        let vx = (128.0 - sr / count as f32) / 127.0;
        let vy = (sg / count as f32 - 128.0) / 127.0;
        (vx * vx + vy * vy).sqrt().clamp(0.0, 1.0)
    }

    pub fn flood_fill_active(&mut self, u: f32, v: f32, threshold: f32, target: &str) -> bool {
        let reference = match &self.reference {
            Some(r) => r.clone(),
            None => return false,
        };
        let active_id = self.active.clone();
        let layer = match self.layer(&active_id) {
            Some(l) => l,
            None => return false,
        };
        let is_adj = matches!(layer.p.kind, LayerKind::Wind | LayerKind::Obstacle);
        // Same rule as `stroke`: on an adjustment layer the wand edits the mask.
        let is_mask = is_adj;
        let _ = target;

        let n = self.size;
        let sx = (u * n as f32).clamp(0.0, n as f32 - 1.0) as usize;
        let sy = (v * n as f32).clamp(0.0, n as f32 - 1.0) as usize;
        let fill: [u8; 3] = if is_mask { [255, 255, 255] } else { [128, 128, 255] };
        let wrap = matches!(self.projection, Projection::Equirectangular | Projection::Polar);

        let layer = self.layer_mut(&active_id).unwrap();
        let dst: &mut Buf = if is_mask {
            if layer.mask.is_none() {
                layer.mask = Some(Buf::new(n, n));
                layer.p.has_mask = true;
            }
            layer.mask.as_mut().unwrap()
        } else {
            &mut layer.buf
        };
        flood_fill(dst, &reference, sx, sy, threshold, fill, wrap);
        if let Some(l) = self.layer_mut(&active_id) {
            if is_mask {
                l.mask_dirty = true;
            } else {
                l.buf_dirty = true;
            }
        }
        // The wand's footprint is unbounded — it can reach the far side of the
        // canvas from a single click, and on a mask it moves the whole blurred
        // obstacle plane with it.
        self.full_dirty = true;
        self.invalidate_accum();
        true
    }

    pub fn clear_layer(&mut self, id: &str) {
        let n = self.size;
        if let Some(l) = self.layer_mut(id) {
            l.buf = Buf::new(n, n);
            // A path layer's pixels are its paths, so clearing it means
            // dropping them — not just wiping the raster.
            l.paths.clear();
            if l.mask.is_some() {
                // Clearing a mask removes the obstacle, not adds it.
                l.mask = Some(Buf::new(n, n));
            }
            l.wind_dirty = true;
            l.buf_dirty = true;
            l.mask_dirty = true;
            l.blur_cache = None;
            l.plane_cache = None;
        }
        self.full_dirty = true;
        self.invalidate_accum();
    }

    // -- paths ---------------------------------------------------------------

    /**
     * Replace a path layer's paths and re-render only what they covered.
     *
     * The dirty rectangle is the union of the old and new bounds of *the paths
     * that actually changed*, not of the layer. That is what makes dragging an
     * anchor interactive: with twenty paths on a layer, moving one of them
     * rebuilds a few hundred pixels, not the whole canvas — and a full-canvas
     * rebuild would mean shipping a 4 MB base64 snapshot per pointer event.
     */
    pub fn set_paths(&mut self, id: &str, paths: Vec<PathData>) {
        let n = self.size;
        let changed = {
            let Some(l) = self.layer(id) else { return };
            if l.p.kind != LayerKind::Path {
                return;
            }
            if l.paths.is_empty() && paths.is_empty() {
                return;
            }
            // Which entries differ? The frontend sends the whole list but
            // almost always edits one path, so an index-wise compare gets the
            // tight rectangle without any bookkeeping.
            let mut rect: Option<(usize, usize, usize, usize)> = None;
            for i in 0..l.paths.len().max(paths.len()) {
                let old = l.paths.get(i);
                let new = paths.get(i);
                if matches!((old, new), (Some(o), Some(nw)) if o == nw) {
                    continue;
                }
                for b in [old, new] {
                    if let Some(b) = b.and_then(|p| path::bounds(p, n)) {
                        rect = merge_rect(rect, b);
                    }
                }
            }
            rect
        };

        let Some(l) = self.layer_mut(id) else { return };
        l.paths = paths;
        // Only the rectangle that moved is re-rendered. A path layer is meant
        // to hold dozens of paths, and dragging one of them should not cost
        // what drawing all of them cost.
        match changed {
            Some(r) => path::regenerate(&mut l.buf, &l.paths, r),
            // Nothing was there before and nothing is now: the layer went from
            // empty to empty, which only a full rebuild can express.
            None => generate_paths(&mut l.buf, &l.paths),
        }
        l.buf_dirty = true;
        // Blur is a full-canvas pass keyed on the buffer — it cannot be
        // patched, so it has to be rebuilt.
        l.blur_cache = None;

        match changed {
            Some(r) => self.pending = merge_rect(self.pending, r),
            None => self.full_dirty = true,
        }
        // The accumulator is a delta against pixels that just changed.
        self.invalidate_accum();
    }

    /** The paths of a layer, for the frontend's overlay and editing. */
    pub fn paths_of(&self, id: &str) -> Vec<PathData> {
        self.layer(id).map(|l| l.paths.clone()).unwrap_or_default()
    }

    // -- effects -------------------------------------------------------------

    /**
     * Replace a layer's effects.
     *
     * Effects are whole-canvas by nature — blur reads a neighbourhood, so
     * changing it moves pixels far outside any dirty rectangle — hence the
     * unconditional full rebuild. It is also cheap to say: the list is a
     * handful of small records, unlike a path or a brush stroke.
     */
    pub fn set_effects(&mut self, id: &str, effects: Vec<LayerEffect>) {
        let Some(l) = self.layer_mut(id) else { return };
        l.p.effects = effects;
        l.p.legacy_blur = 0.0;
        // Keyed on the radius, so it is rebuilt on the next composite.
        l.blur_cache = None;
        self.full_dirty = true;
        self.invalidate_accum();
    }

    // -- history -------------------------------------------------------------

    pub fn save_history(&mut self) {
        let id = self.active.clone();
        let Some(l) = self.layer(&id) else { return };
        // The order comes along even though this step does not move it. Undo
        // rewinds to *this* state, and by the time it does, a later step may
        // have removed a layer — which only the order and the snapshot of the
        // layer that was active here can put back.
        let order: Vec<String> = self.layers.iter().map(|l| l.p.id.clone()).collect();
        self.push_history(vec![snapshot_of(l)], Some(order));
    }

    /**
     * Record the state *before* a step that changes the shape of the stack.
     *
     * `ids` are the layers the step is about to rewrite; the whole stack's
     * order comes along too, because putting a removed layer back is the only
     * way undo can mean anything here.
     *
     * A history entry records the state *after* the step it belongs to, so a
     * step that removes a layer has to write two: this one, and one after the
     * removal — otherwise undo would rewind past the merge entirely and land
     * on whichever entry came before it, which knows nothing about the layer
     * that got merged away.
     */
    fn save_history_stack(&mut self, ids: &[String]) {
        let snaps: Vec<LayerSnapshot> = ids
            .iter()
            .filter_map(|id| self.layer(id).map(snapshot_of))
            .collect();
        if snaps.is_empty() {
            return;
        }
        let order: Vec<String> = self.layers.iter().map(|l| l.p.id.clone()).collect();
        self.push_history(snaps, Some(order));
    }

    fn push_history(&mut self, layers: Vec<LayerSnapshot>, order: Option<Vec<String>>) {
        self.history.truncate(self.hist_idx);
        self.history.push(HistoryEntry { layers, order });
        self.hist_idx = self.history.len();
        if self.history.len() > 40 {
            self.history.remove(0);
            self.hist_idx -= 1;
        }
    }

    fn restore(&mut self, idx: usize) {
        self.invalidate_accum();
        let Some(entry) = self.history.get(idx).cloned() else { return };
        let expect = self.size * self.size * 4;
        let n = self.size;

        // The shape first, because a layer that is not in the stack cannot be
        // restored into. Only attempted when every id can be accounted for —
        // otherwise rebuilding would silently drop a layer that exists now and
        // that this step knows nothing about.
        let can_rebuild = entry.order.as_ref().map(|order| {
            order.iter().all(|id| {
                self.layers.iter().any(|l| &l.p.id == id)
                    || entry.layers.iter().any(|s| &s.p.id == id)
            })
        });
        if let (Some(order), Some(true)) = (&entry.order, can_rebuild) {
            let mut have = std::mem::take(&mut self.layers);
            self.layers = order
                .iter()
                .filter_map(|id| {
                    match have.iter().position(|l| &l.p.id == id) {
                        Some(i) => Some(have.remove(i)),
                        // Removed by the step: rebuild it from the snapshot it
                        // brought along.
                        None => entry.layers.iter().find(|s| &s.p.id == id).map(|s| {
                            LayerData {
                                p: s.p.clone(),
                                buf: Buf { w: n, h: n, data: decompress(&s.buf, expect) },
                                mask: s.mask.as_ref().map(|m| Buf {
                                    w: n,
                                    h: n,
                                    data: decompress(m, expect),
                                }),
                                paths: s.paths.clone(),
                                wind_dirty: true,
                                buf_dirty: true,
                                mask_dirty: true,
                                blur_cache: None,
                                plane_cache: None,
                            }
                        }),
                    }
                })
                .collect();
        }

        for s in &entry.layers {
            if let Some(l) = self.layer_mut(&s.p.id) {
                l.p = s.p.clone();
                l.buf.data = decompress(&s.buf, expect);
                l.mask = s.mask.as_ref().map(|m| Buf { w: n, h: n, data: decompress(m, expect) });
                l.paths = s.paths.clone();
                l.wind_dirty = true;
                l.buf_dirty = true;
                l.mask_dirty = true;
                l.blur_cache = None;
                l.plane_cache = None;
            }
        }
        if !self.layers.iter().any(|l| l.p.id == self.active) {
            if let Some(last) = self.layers.last() {
                self.active = last.p.id.clone();
            }
        }
        self.full_dirty = true;
    }

    pub fn undo(&mut self) -> bool {
        if self.hist_idx > 1 {
            self.hist_idx -= 1;
            let i = self.hist_idx - 1;
            self.restore(i);
            true
        } else {
            false
        }
    }

    pub fn redo(&mut self) -> bool {
        if self.hist_idx < self.history.len() {
            self.hist_idx += 1;
            let i = self.hist_idx - 1;
            self.restore(i);
            true
        } else {
            false
        }
    }

    /// How far an edit to this layer's mask reaches, in canvas pixels. 0 for
    /// anything that is not an obstacle carrying a disturbance effect: those
    /// contribute pointwise, so a dab only ever moves its own footprint.
    fn obstacle_reach(l: &LayerData) -> usize {
        if l.p.kind != LayerKind::Obstacle {
            return 0;
        }
        let d = disturbance_amount(&l.p.effects);
        if d <= 0.0 {
            return 0;
        }
        obstacle_influence(d)
    }

    /// `r` grown by `pad`, clipped to the canvas.
    fn grow_rect(
        r: (usize, usize, usize, usize),
        pad: usize,
        n: usize,
    ) -> (usize, usize, usize, usize) {
        let (x, y, w, h) = r;
        if w == 0 || h == 0 {
            return r;
        }
        let x0 = x.saturating_sub(pad);
        let y0 = y.saturating_sub(pad);
        let x1 = (x + w + pad).min(n);
        let y1 = (y + h + pad).min(n);
        (x0, y0, x1.saturating_sub(x0), y1.saturating_sub(y0))
    }

    // -- compositing ---------------------------------------------------------

    /// Rebuild the composite — only the rectangle that can actually have
    /// changed.
    ///
    /// Every step that feeds the composite is pointwise: blend, mask, the
    /// obstacle B channel, and the disturbance all read one pixel of their
    /// input to write one pixel of output. So "where the layer changed" *is*
    /// "where the composite changes". Blur is the one exception — it has a
    /// neighbourhood, accounted for by growing the rectangle by
    /// `blur_influence`.
    ///
    /// That is the whole trick, and it is the difference between paying for a
    /// 64px dab and paying for a 1024px recomposite: measured 265 ms -> ~1 ms
    /// on a 1024 canvas.
    pub fn composite(&mut self) {
        let n = self.size;
        if n == 0 {
            return;
        }

        // Derived data first. These depend on layer *parameters*, not on where
        // the brush went, so they are rebuilt only when their input moved —
        // and when they do move, they move everywhere.
        let proj = self.projection;
        let polar = self.polar_angle;
        let mut global = self.full_dirty;

        for l in self.layers.iter_mut() {
            if l.p.kind == LayerKind::Wind && l.wind_dirty {
                generate_wind(&mut l.buf, l.p.direction, l.p.strength, proj, polar);
                l.wind_dirty = false;
                global = true;
            }
            // Effects apply to whatever a layer's *content* is — painted
            // pixels, rasterised paths, or the generated wind field. Not to an
            // obstacle layer: what it contributes is a mask and a disturbance
            // plane, and it already has its own softening dial.
            let radius = if matches!(l.p.kind, LayerKind::Wind | LayerKind::Paint | LayerKind::Path) {
                blur_amount(&l.p.effects)
            } else {
                0.0
            };
            if radius > 0.0 {
                let stale = l.blur_cache.as_ref().map(|c| c.0 != radius).unwrap_or(true);
                if l.buf_dirty || stale {
                    let b = blur(&l.buf, radius);
                    l.blur_cache = Some((radius, b));
                    l.buf_dirty = false;
                    // A different radius rewrites the whole blurred field.
                    if stale {
                        global = true;
                    }
                }
            } else if l.blur_cache.take().is_some() {
                // Radius went to zero, so the cached copy must not be used
                // again — and the un-blurred buffer is what shows now.
                global = true;
            }
            if l.p.kind == LayerKind::Obstacle {
                // The mask alone is a cut-out: it writes the B channel and
                // nothing else, which costs one pass. The *disturbance* is the
                // expensive part — a downsampled blur of the whole mask — and
                // it is now an effect you have to ask for, so an obstacle that
                // is just a mask never builds a plane at all.
                let dist = disturbance_amount(&l.p.effects);
                let want = l.mask.is_some() && dist > 0.0;
                if !want {
                    l.plane_cache = None;
                } else {
                    let stale = l.plane_cache.as_ref().map(|c| c.0 != dist).unwrap_or(true);
                    if l.mask_dirty || stale {
                        let (plane, lw, lh, ss) = {
                            let m = l.mask.as_ref().unwrap();
                            obstacle_alpha_plane(m, dist)
                        };
                        l.plane_cache = Some((dist, plane, lw, lh, ss));
                        l.mask_dirty = false;
                        // A mask edit moves the plane within `obstacle_reach`
                        // of the brush and no further, and `pending` already
                        // covers that. Only a new *disturbance* rewrites the
                        // whole field.
                        if stale {
                            global = true;
                        }
                    }
                }
            }
        }

        let (rx, ry, rw, rh) = if global {
            (0usize, 0usize, n, n)
        } else {
            match self.pending {
                Some(r) => r,
                // Nothing changed since the last composite.
                None => {
                    self.last_region = (0, 0, 0, 0);
                    return;
                }
            }
        };
        if rw == 0 || rh == 0 {
            self.last_region = (0, 0, 0, 0);
            return;
        }

        let pad = self.layers
            .iter()
            .filter(|l| l.p.visible && matches!(l.p.kind, LayerKind::Wind | LayerKind::Paint | LayerKind::Path))
            .map(|l| blur_influence(blur_amount(&l.p.effects)))
            .max()
            .unwrap_or(0);
        let x0 = rx.saturating_sub(pad);
        let y0 = ry.saturating_sub(pad);
        let x1 = (rx + rw + pad).min(n);
        let y1 = (ry + rh + pad).min(n);
        if x1 <= x0 || y1 <= y0 {
            self.last_region = (0, 0, 0, 0);
            return;
        }
        let stride = n * 4;

        // `prev_composite` is only ever read inside the rectangle the next
        // composite rebuilds, and that run refreshes the strip itself — so
        // there is no need to copy the whole canvas here.
        {
            let (prev, comp) = (&mut self.prev_composite, &self.composite);
            prev.data[y0 * stride..y1 * stride]
                .copy_from_slice(&comp.data[y0 * stride..y1 * stride]);
        }

        // Reuse both scratch allocations so a composite never allocates.
        // Outside the rectangle `acc` still holds the previous result, which is
        // exactly what belongs there.
        let mut acc = std::mem::replace(&mut self.scratch, Buf::new(0, 0));
        acc.w = n;
        acc.h = n;
        acc.data.resize(n * n * 4, 0);
        let mut helper = std::mem::replace(&mut self.scratch2, Buf::new(0, 0));
        helper.w = n;
        helper.h = n;
        helper.data.resize(n * n * 4, 0);

        fill_neutral(&mut acc, x0, x1, y0, y1);

        // Layers composite in array order, so the last one sits on top — the
        // same reading as the layer list, whose first row is the top layer.
        for i in 0..self.layers.len() {
            let l = &self.layers[i];
            if !l.p.visible {
                continue;
            }
            let op = l.p.opacity;
            match l.p.kind {
                // A path layer composites exactly like a paint layer: by the
                // time we get here its buffer has already been rasterised from
                // its paths, and the stack below it does not care how the
                // pixels got there.
                LayerKind::Paint | LayerKind::Path => {
                    let src: &Buf = match &l.blur_cache {
                        Some(c) if c.0 > 0.0 => &c.1,
                        _ => &l.buf,
                    };
                    blend_over(&mut acc, src, op, x0, x1, y0, y1);
                }
                LayerKind::Wind => {
                    let src: &Buf = match &l.blur_cache {
                        Some(c) if c.0 > 0.0 => &c.1,
                        _ => &l.buf,
                    };
                    match &l.mask {
                        Some(mask) => {
                            copy_rect(&mut helper, src, x0, x1, y0, y1);
                            mask_in(&mut helper, mask, x0, x1, y0, y1);
                            blend_over(&mut acc, &helper, op, x0, x1, y0, y1);
                        }
                        None => blend_over(&mut acc, src, op, x0, x1, y0, y1),
                    }
                }
                LayerKind::Obstacle => {
                    let Some(mask) = &l.mask else { continue };
                    if let Some((_, plane, lw, lh, ss)) = &l.plane_cache {
                        let (lw, lh, ss) = (*lw, *lh, *ss);
                        apply_disturbance(&mut acc, plane, lw, lh, ss, x0, x1, y0, y1);
                    }
                    // B channel: how *blocked* this pixel is, accumulated over
                    // the masks that cover it, the same over everything else in
                    // the stack uses.
                    //
                    // It used to be "last writer wins" — `B = 255 - alpha` —
                    // which let a mask whose alpha was 2 wipe out one whose
                    // alpha was 239 underneath it, and made two obstacle
                    // layers impossible to merge into one without the picture
                    // changing.
                    //
                    // It is done *before* the neutral blend below, because that
                    // blend carries B = 255 (fully mobile) and would otherwise
                    // wash the accumulated value back out.
                    each_row_pair(&mut acc, mask, y0, y1, |drow, srow| {
                        for x in x0..x1 {
                            let a = srow[x * 4 + 3] as f32 / 255.0 * op;
                            if a <= 0.0 {
                                continue;
                            }
                            let blocked = 1.0 - drow[x * 4 + 2] as f32 / 255.0;
                            let now = blocked * (1.0 - a) + a;
                            drow[x * 4 + 2] = ((1.0 - now) * 255.0).clamp(0.0, 255.0) as u8;
                        }
                    });
                    fill_neutral(&mut helper, x0, x1, y0, y1);
                    mask_in(&mut helper, mask, x0, x1, y0, y1);
                    blend_over_rg(&mut acc, &helper, op, x0, x1, y0, y1);
                    // B channel: 255 - obstacle alpha.
                    //
                    // Written *here*, in stack order, rather than in a second
                    // pass after the loop. Doing it afterwards made the
                    // obstacle unconditional: however much flow you painted on
                    // layers above it, the pixel stayed flagged as an obstacle.
                    // Writing it in place means a layer stacked on top covers
                    // it again, exactly like any other channel.
                    each_row_pair(&mut acc, mask, y0, y1, |drow, srow| {
                        for x in x0..x1 {
                            let a = srow[x * 4 + 3] as f32 / 255.0 * op;
                            if a <= 0.0 {
                                continue;
                            }
                            // How *blocked* this pixel already is, composited
                            // with this mask over it — the same over the rest
                            // of the stack uses, rather than "last writer
                            // wins".
                            //
                            // Last-writer-wins meant a mask whose alpha was 2
                            // wiped out one whose alpha was 239 underneath,
                            // and it also made two obstacle layers impossible
                            // to merge into one without changing the picture.
                            let blocked = 1.0 - drow[x * 4 + 2] as f32 / 255.0;
                            let now = blocked * (1.0 - a) + a;
                            drow[x * 4 + 2] = ((1.0 - now) * 255.0).clamp(0.0, 255.0) as u8;
                        }
                    });
                }
            }
        }

        std::mem::swap(&mut acc, &mut self.composite);
        self.scratch = acc;
        self.scratch2 = helper;
        self.last_region = (x0, y0, x1 - x0, y1 - y0);
    }

    /// Compute the bounding box that changed between the last two composites.
    ///
    /// Scans only the rectangle `composite` rebuilt, which is what makes the
    /// diff cost like the edit instead of like the canvas. That is sound
    /// because nothing outside that rectangle was touched: every step in
    /// `composite` is pointwise (bar blur, whose margin is already folded into
    /// the rectangle).
    pub fn dirty_rect(&self) -> (usize, usize, usize, usize) {
        if self.full_dirty {
            return (0, 0, self.size, self.size);
        }
        let (bx, by, bw, bh) = self.last_region;
        if bw == 0 || bh == 0 {
            return (0, 0, 0, 0);
        }
        let n = self.size;
        let a = &self.prev_composite.data;
        let b = &self.composite.data;
        let stride = n * 4;

        // Row scan. Parallel only when there are enough rows to pay for it.
        let row_hit = |y: usize| -> bool {
            let s = y * stride + bx * 4;
            a[s..s + bw * 4] != b[s..s + bw * 4]
        };
        let (y0, y1) = if bh >= PAR_MIN_ROWS {
            (by..by + bh).into_par_iter().filter(|&y| row_hit(y))
                .fold(|| (usize::MAX, 0usize), |m, y| (m.0.min(y), m.1.max(y)))
                .reduce(|| (usize::MAX, 0usize), |p, q| (p.0.min(q.0), p.1.max(q.1)))
        } else {
            (by..by + bh).filter(|&y| row_hit(y))
                .fold((usize::MAX, 0usize), |m, y| (m.0.min(y), m.1.max(y)))
        };
        if y0 == usize::MAX {
            return (0, 0, 0, 0);
        }

        let col_hit = |x: usize| -> bool {
            (y0..=y1).any(|y| {
                let i = y * stride + x * 4;
                a[i..i + 4] != b[i..i + 4]
            })
        };
        let (x0, x1) = if bw >= PAR_MIN_ROWS {
            (bx..bx + bw).into_par_iter().filter(|&x| col_hit(x))
                .fold(|| (usize::MAX, 0usize), |m, x| (m.0.min(x), m.1.max(x)))
                .reduce(|| (usize::MAX, 0usize), |p, q| (p.0.min(q.0), p.1.max(q.1)))
        } else {
            (bx..bx + bw).filter(|&x| col_hit(x))
                .fold((usize::MAX, 0usize), |m, x| (m.0.min(x), m.1.max(x)))
        };
        if x0 == usize::MAX {
            return (0, 0, 0, 0);
        }
        (x0, y0, x1 - x0 + 1, y1 - y0 + 1)
    }

    pub fn clear_dirty(&mut self) {
        self.full_dirty = false;
        self.pending = None;
        // `prev_composite` is deliberately *not* refreshed here. It is only
        // read inside the rectangle the next `composite` rebuilds, and that run
        // copies the strip itself — so the full-canvas copy this used to do was
        // pure per-frame overhead.
    }
}

