fn merge_rect(
    a: Option<(usize, usize, usize, usize)>,
    b: (usize, usize, usize, usize),
) -> Option<(usize, usize, usize, usize)> {
    if b.2 == 0 || b.3 == 0 {
        return a;
    }
    Some(match a {
        None => b,
        Some((ax, ay, aw, ah)) => {
            let x0 = ax.min(b.0);
            let y0 = ay.min(b.1);
            let x1 = (ax + aw).max(b.0 + b.2);
            let y1 = (ay + ah).max(b.1 + b.3);
            (x0, y0, x1 - x0, y1 - y0)
        }
    })
}

/// Stamp with horizontal wrap-around so equirect seams stay continuous.
fn stamp_wrap(
    dst: &mut Buf,
    x: f32, y: f32, lx: f32, ly: f32,
    size: f32, hardness: f32, style: &StampStyle,
    mut accum: Option<&mut [u8]>,
) -> (usize, usize, usize, usize) {
    let n = dst.w as f32;
    let dx = x - lx;
    if dx.abs() > n * 0.5 {
        if dx > 0.0 {
            let a = stamp(dst, x - n, y, lx, ly, size, hardness, style, accum.as_deref_mut());
            let b = stamp(dst, x, y, lx + n, ly, size, hardness, style, accum.as_deref_mut());
            merge_rect(Some(a), b).unwrap()
        } else {
            let a = stamp(dst, x + n, y, lx, ly, size, hardness, style, accum.as_deref_mut());
            let b = stamp(dst, x, y, lx - n, ly, size, hardness, style, accum.as_deref_mut());
            merge_rect(Some(a), b).unwrap()
        }
    } else {
        let r = stamp(dst, x, y, lx, ly, size, hardness, style, accum.as_deref_mut());
        let radius = size / 2.0;
        let mut out = r;
        if x < radius || lx < radius {
            let e = stamp(dst, x + n, y, lx + n, ly, size, hardness, style, accum.as_deref_mut());
            out = merge_rect(Some(out), e).unwrap_or(out);
        }
        if x > n - radius || lx > n - radius {
            let e = stamp(dst, x - n, y, lx - n, ly, size, hardness, style, accum.as_deref_mut());
            out = merge_rect(Some(out), e).unwrap_or(out);
        }
        out
    }
}

/// Walk rows `y0..y1` of `dst` together with the matching rows of `src`.
///
/// Parallel above `PAR_MIN_ROWS`, sequential below it. Handing a 40-row brush
/// rectangle to the thread pool costs more than running it — the scheduling is
/// a fixed ~0.1 ms per call, and a composite makes half a dozen of them.
fn each_row_pair<F>(dst: &mut Buf, src: &Buf, y0: usize, y1: usize, f: F)
where
    F: Fn(&mut [u8], &[u8]) + Sync + Send,
{
    let stride = dst.w * 4;
    let d = &mut dst.data[y0 * stride..y1 * stride];
    let s = &src.data[y0 * stride..y1 * stride];
    if y1 - y0 >= PAR_MIN_ROWS {
        d.par_chunks_mut(stride).zip(s.par_chunks(stride)).for_each(|(a, b)| f(a, b));
    } else {
        d.chunks_mut(stride).zip(s.chunks(stride)).for_each(|(a, b)| f(a, b));
    }
}

/// Walk rows `y0..y1` of `dst`. Same parallel / sequential split as
/// `each_row_pair`.
fn each_row_mut<F>(dst: &mut Buf, y0: usize, y1: usize, f: F)
where
    F: Fn(&mut [u8]) + Sync + Send,
{
    let stride = dst.w * 4;
    let d = &mut dst.data[y0 * stride..y1 * stride];
    if y1 - y0 >= PAR_MIN_ROWS {
        d.par_chunks_mut(stride).for_each(f);
    } else {
        d.chunks_mut(stride).for_each(f);
    }
}

/// source-over with a global alpha multiplier, over `[x0, x1) x [y0, y1)`
fn blend_over(dst: &mut Buf, src: &Buf, opacity: f32, x0: usize, x1: usize, y0: usize, y1: usize) {
    each_row_pair(dst, src, y0, y1, |d, s| {
        for x in x0..x1 {
            let i = x * 4;
            let sa = s[i + 3] as f32 / 255.0 * opacity;
            if sa <= 0.0 {
                continue;
            }
            let inv = 1.0 - sa;
            d[i] = (s[i] as f32 * sa + d[i] as f32 * inv) as u8;
            d[i + 1] = (s[i + 1] as f32 * sa + d[i + 1] as f32 * inv) as u8;
            d[i + 2] = (s[i + 2] as f32 * sa + d[i + 2] as f32 * inv) as u8;
            d[i + 3] = (sa * 255.0 + d[i + 3] as f32 * inv).min(255.0) as u8;
        }
    });
}

/**
 * `blend_over` for a layer that owns its B channel elsewhere.
 *
 * An obstacle mask carries a neutral pixel whose B is 255 — "fully mobile" —
 * which is the opposite of what the mask means. So the mask's contribution to
 * B is written separately (see the obstacle branch of `composite`) and this
 * blend leaves B alone.
 */
fn blend_over_rg(dst: &mut Buf, src: &Buf, opacity: f32, x0: usize, x1: usize, y0: usize, y1: usize) {
    each_row_pair(dst, src, y0, y1, |d, s| {
        for x in x0..x1 {
            let i = x * 4;
            let sa = s[i + 3] as f32 / 255.0 * opacity;
            if sa <= 0.0 {
                continue;
            }
            let inv = 1.0 - sa;
            d[i] = (s[i] as f32 * sa + d[i] as f32 * inv) as u8;
            d[i + 1] = (s[i + 1] as f32 * sa + d[i + 1] as f32 * inv) as u8;
            d[i + 3] = (sa * 255.0 + d[i + 3] as f32 * inv).min(255.0) as u8;
        }
    });
}

/// destination-in: keep src RGB but multiply alpha by the mask
fn mask_in(dst: &mut Buf, mask: &Buf, x0: usize, x1: usize, y0: usize, y1: usize) {
    each_row_pair(dst, mask, y0, y1, |d, m| {
        for x in x0..x1 {
            let i = x * 4;
            d[i + 3] = ((d[i + 3] as f32) * (m[i + 3] as f32 / 255.0)) as u8;
        }
    });
}

/**
 * Flatten `src` over `dst` into one buffer at full opacity, both layers'
 * opacities folded in.
 *
 * **Not** `blend_over`. That one is written for the composite, where the
 * destination is the running accumulation and is therefore always opaque — so
 * it can skip multiplying the destination's colour by its alpha. Here the
 * destination is an ordinary layer whose alpha is whatever was painted, and
 * skipping that factor would leave the lower layer's colour at full strength
 * under a half-covered pixel.
 *
 * Doing it in premultiplied space and dividing through by the resulting alpha
 * is what makes the result *exactly* what the two layers produced, rather than
 * an approximation of it: `over` is associative, and opacity only ever enters
 * as `alpha * opacity`.
 */
fn merge_over(dst: &mut Buf, src: &Buf, dst_op: f32, src_op: f32) {
    each_row_pair(dst, src, 0, dst.h, |d, s| {
        for px in 0..(d.len() / 4) {
            let i = px * 4;
            let ad = d[i + 3] as f32 / 255.0 * dst_op;
            let as_ = s[i + 3] as f32 / 255.0 * src_op;
            let ao = as_ + ad * (1.0 - as_);
            if ao <= 0.0 {
                d[i + 3] = 0;
                continue;
            }
            for c in 0..3 {
                let v = s[i + c] as f32 * as_ + d[i + c] as f32 * ad * (1.0 - as_);
                d[i + c] = (v / ao).clamp(0.0, 255.0) as u8;
            }
            d[i + 3] = (ao * 255.0).min(255.0) as u8;
        }
    });
}

/// Multiply every alpha by `f`, leaving the colour alone.
///
/// This is what folds a layer's opacity into its pixels, and it is why a merge
/// can be exact: `blend_over` only ever reads `alpha * opacity`, so scaling the
/// alpha by the opacity and then dropping the opacity changes nothing.
fn scale_alpha(b: &mut Buf, f: f32) {
    if (f - 1.0).abs() < 1e-4 {
        return;
    }
    each_row_mut(b, 0, b.h, |row| {
        for px in row.chunks_exact_mut(4) {
            px[3] = (px[3] as f32 * f) as u8;
        }
    });
}

/// Reset a rectangle to the neutral flow value.
fn fill_neutral(dst: &mut Buf, x0: usize, x1: usize, y0: usize, y1: usize) {
    each_row_mut(dst, y0, y1, |row| {
        for x in x0..x1 {
            row[x * 4..x * 4 + 4].copy_from_slice(&buf::NEUTRAL);
        }
    });
}

/// Copy a rectangle from one buffer to another.
fn copy_rect(dst: &mut Buf, src: &Buf, x0: usize, x1: usize, y0: usize, y1: usize) {
    each_row_pair(dst, src, y0, y1, |d, s| {
        d[x0 * 4..x1 * 4].copy_from_slice(&s[x0 * 4..x1 * 4]);
    });
}

fn snapshot_of(l: &LayerData) -> LayerSnapshot {
    LayerSnapshot {
        p: l.p.clone(),
        buf: compress(&l.buf.data),
        mask: l.mask.as_ref().map(|m| compress(&m.data)),
        // Undo has to restore the paths too, or a step back would put the old
        // pixels back under the new geometry and the two would disagree the
        // moment you touched an anchor again.
        paths: l.paths.clone(),
    }
}

fn compress(data: &[u8]) -> Vec<u8> {
    zstd::stream::encode_all(data, 1).unwrap_or_else(|_| data.to_vec())
}

fn decompress(data: &[u8], expect: usize) -> Vec<u8> {
    match zstd::stream::decode_all(data) {
        Ok(v) if v.len() == expect => v,
        _ => vec![0u8; expect],
    }
}
