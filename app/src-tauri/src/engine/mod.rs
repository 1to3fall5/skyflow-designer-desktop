#[derive(Clone, Serialize, Deserialize, Debug, PartialEq)]
pub enum LayerKind {
    Paint,
    Wind,
    Obstacle,
    /// Pixels are generated by rasterising `paths`, so a stroke you drew an
    /// hour ago is still an object you can pick up and move.
    Path,
}

#[derive(Clone, Serialize, Deserialize)]
pub struct LayerParams {
    pub id: String,
    pub name: String,
    pub kind: LayerKind,
    pub visible: bool,
    pub opacity: f32,
    /// What is *done to* this layer: see `effect.rs`. A list, not a `blur`
    /// field, so an effect can be added, switched off and removed without
    /// losing the number it was tuned to.
    #[serde(default)]
    pub effects: Vec<LayerEffect>,
    /// Read-only: projects saved before effects existed carried a bare radius.
    /// `io::load_project` turns a v1 file's radius into a blur effect; this
    /// field exists only so the migration has somewhere to land.
    #[serde(default)]
    pub legacy_blur: f32,
    // wind
    pub direction: f32,
    pub strength: f32,
    pub has_mask: bool,
}

pub struct LayerData {
    pub p: LayerParams,
    /// paint content, or cached generated wind field, or rasterised paths
    pub buf: Buf,
    pub mask: Option<Buf>,
    /// The pen paths this layer is made of. Only `Path` layers have any; the
    /// field lives here so undo, save and load get it for free.
    pub paths: Vec<PathData>,
    pub wind_dirty: bool,
    /// `buf` was rewritten since `blur_cache` was built.
    pub buf_dirty: bool,
    /// `mask` was rewritten since `plane_cache` was built.
    pub mask_dirty: bool,
    /// Blurred copy of `buf`, keyed by the radius it was built with.
    ///
    /// Blur is the one composite input that costs six full-canvas passes, and
    /// it does not change while you paint somewhere else.
    pub blur_cache: Option<(f32, Buf)>,
    /// Blurred obstacle alpha plane, keyed by the disturbance it was built
    /// with. Same reasoning as `blur_cache` — this one also downsamples and
    /// blurs, every frame, for a mask that rarely moves.
    pub plane_cache: Option<(f32, Vec<u8>, usize, usize, usize)>,
}

#[derive(Clone, Serialize, Deserialize)]
pub struct LayerSnapshot {
    pub p: LayerParams,
    pub buf: Vec<u8>,
    pub mask: Option<Vec<u8>>,
    /// `default` so a project saved before paths existed still opens.
    #[serde(default)]
    pub paths: Vec<PathData>,
}

